//! What the calculator's card says about currencies: their names and signs.

/// The English name of an ISO 4217 code, for the codes ExchangeRate-API has.
pub fn name(code: &str) -> Option<&'static str> {
    let code = code.to_ascii_uppercase();
    NAMES
        .iter()
        .find(|(known, _)| *known == code)
        .map(|&(_, name)| name)
}

/// `0.12 USD` as people write it, `$0.12`, for currencies whose sign is
/// unambiguous; the rest keep their code.
pub fn with_sign(amount: &str, code: &str) -> String {
    let sign = match code.to_ascii_uppercase().as_str() {
        "USD" => "$",
        "EUR" => "€",
        "GBP" => "£",
        "JPY" => "¥",
        "UAH" => "₴",
        "INR" => "₹",
        "KRW" => "₩",
        "ILS" => "₪",
        "TRY" => "₺",
        "PLN" => return format!("{amount} zł"),
        _ => return format!("{amount} {}", code.to_ascii_uppercase()),
    };
    match amount.strip_prefix('-') {
        Some(amount) => format!("-{sign}{amount}"),
        None => format!("{sign}{amount}"),
    }
}

